    base = set(STRINGS[DEFAULT_LANG])
    for lang, table in STRINGS.items():
        missing, extra = base - set(table), set(table) - base
        status = "OK" if not (missing or extra) else f"missing={sorted(missing)} extra={sorted(extra)}"
        print(f"{lang}: {len(table)} keys, {status}")
