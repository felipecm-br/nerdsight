class Translator:
    """Looks up and formats UI strings for one language, falling back to English."""

    def __init__(self, lang: str):
        self.lang = lang if lang in STRINGS else DEFAULT_LANG
        self._strings = STRINGS[self.lang]

    def __call__(self, key: str, **kwargs) -> str:
        text = self._strings.get(key) or STRINGS[DEFAULT_LANG][key]
        return text.format(**kwargs) if kwargs else text

    def int(self, n: int) -> str:
        return f"{n:,}".replace(",", self("thousands_sep"))

    def decimal(self, x: float, digits: int = 1) -> str:
        return f"{x:.{digits}f}".replace(".", self("decimal_sep"))

    def js_strings(self) -> dict[str, str]:
        return {k.removeprefix("js_"): v for k, v in self._strings.items() if k.startswith("js_")} | {
            "search_label": self("search_label"),
            "filter_label": self("filter_label"),
            "lang": self.lang,
        }


